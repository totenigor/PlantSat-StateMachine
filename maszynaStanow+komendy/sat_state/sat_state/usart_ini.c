#include "usart_ini.h"

void USART0_ini(uint16_t baud)
{
	USART0.BAUD = (uint16_t)((64.0 * F_CPU) / (16.0 * baud) + 0.5);;
	USART0.CTRLC |= USART_CMODE_ASYNCHRONOUS_gc;	//USART OPERATING ASYNCHRONOUS MODE
	USART0.CTRLC |= USART_PMODE_DISABLED_gc;		//PARITY MODE DISABLED
	USART0.CTRLC |= USART_SBMODE_1BIT_gc;			//1 BIT STOP
	USART0.CTRLC |= USART_CHSIZE_8BIT_gc;			//USART WORKING WITH 8 BITS PER FRAME
	PORTA.DIRSET = PIN0_bm;							//SETTING TxD PIN AS OUTPUT
	USART0.CTRLB |= USART_TXEN_bm;					//TRANSMITTER ENABLED
	USART0.CTRLB |= USART_RXEN_bm;					//RECEIVER ENABLED
	USART0.CTRLA |= USART_RXCIE_bm;					//RECEIVE COMPLETE INTERRUPT ENABLED
}

void USART1_ini(uint16_t baud)
{
	USART1.BAUD = (uint16_t)((64.0 * F_CPU) / (16.0 * baud) + 0.5);
	
	
	USART1.CTRLC = USART_CMODE_ASYNCHRONOUS_gc		//ASYNCHRONOUS, 8 BIT, 1 BIT STOP
	| USART_PMODE_DISABLED_gc
	| USART_SBMODE_1BIT_gc
	| USART_CHSIZE_8BIT_gc;


	PORTC.DIRSET = PIN0_bm;    // SET PC0 (TXD1) TO OUTPUT
	
	USART1.CTRLB = USART_TXEN_bm | USART_RXEN_bm;	//RX & TX ENABLE
	//USART1.CTRLA = USART_RXCIE_bm;				//RX INTERRUPT ENABLE
}